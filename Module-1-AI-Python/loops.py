# Python Loops

# For Loop
print("For Loop:")

for number in range(1, 6):
    print(number)

# Even Numbers
print("\nEven Numbers:")

for number in range(1, 11):
    if number % 2 == 0:
        print(number)

# While Loop
print("\nWhile Loop:")

count = 1

while count <= 5:
    print(count)
    count += 1
