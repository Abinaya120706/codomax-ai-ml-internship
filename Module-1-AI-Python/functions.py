# Python Functions

# Function to greet a person
def greet(name):
    return "Hello, " + name


# Function to add two numbers
def add(a, b):
    return a + b


# Function to find the square of a number
def square(number):
    return number * number


# Calling the functions
print(greet("Abinaya"))
print("Addition:", add(10, 20))
print("Square:", square(5))
